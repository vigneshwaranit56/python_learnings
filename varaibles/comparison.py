b = 3

age = 25
# comparison operators and their explanations
print(a == b) # checks if a is equal to b
print(a != b) # checks if a is not equal to b
print(a > b) # checks if a is greater than b
print(a < b) # checks if a is less than b
print(a >= b) # checks if a is greater than or equal to b
print(a <= b) # checks if a is less than or equal to b

#Logical operators and their explanations
print(age >= 18 and age <= 60) # checks if age is between 18 and 60 (inclusive)
print(age >= 18 or age <= 60) # checks if age is either greater than or equal to 18, or less than or equal to 60
print(not(age >= 18 and age <= 60)) # checks if age is not between 18 and 60 (inclusive)